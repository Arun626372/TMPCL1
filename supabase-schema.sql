-- Public storage buckets
insert into storage.buckets (id, name, public) values
  ('player-photos', 'player-photos', true),
  ('id-proofs', 'id-proofs', true),
  ('team-logos', 'team-logos', true),
  ('squad-banners', 'squad-banners', true),
  ('gallery-media', 'gallery-media', true),
  ('partner-logos', 'partner-logos', true),
  ('leadership-photos', 'leadership-photos', true),
  ('news-images', 'news-images', true)
on conflict (id) do update set public = excluded.public;

do $$ begin
  create policy "TMPCL public read storage" on storage.objects for select to anon using (bucket_id in ('player-photos','id-proofs','team-logos','squad-banners','gallery-media','partner-logos','leadership-photos','news-images'));
exception when duplicate_object then null; end $$;
do $$ begin
  create policy "TMPCL public upload storage" on storage.objects for insert to anon with check (bucket_id in ('player-photos','id-proofs','team-logos','squad-banners','gallery-media','partner-logos','leadership-photos','news-images'));
exception when duplicate_object then null; end $$;
do $$ begin
  create policy "TMPCL public update storage" on storage.objects for update to anon using (bucket_id in ('player-photos','id-proofs','team-logos','squad-banners','gallery-media','partner-logos','leadership-photos','news-images')) with check (bucket_id in ('player-photos','id-proofs','team-logos','squad-banners','gallery-media','partner-logos','leadership-photos','news-images'));
exception when duplicate_object then null; end $$;
do $$ begin
  create policy "TMPCL public delete storage" on storage.objects for delete to anon using (bucket_id in ('player-photos','id-proofs','team-logos','squad-banners','gallery-media','partner-logos','leadership-photos','news-images'));
exception when duplicate_object then null; end $$;

