-- TMPCL Supabase Database + Storage Setup
-- Run this full file once in Supabase SQL Editor before testing the website.

create table if not exists public.players (
  id text primary key,
  name text not null,
  mobile text not null,
  city text,
  dob date,
  age integer,
  age_group text,
  role text,
  batting text,
  bowling text,
  experience text,
  email text,
  photo_url text,
  proof_url text,
  fee integer default 999,
  assigned_category text default 'Pending until trials & auction',
  payment_status text default 'Pending',
  created_at timestamptz default now()
);

create table if not exists public.teams (
  id text primary key,
  name text not null,
  city text,
  owner text,
  status text default 'Player Auction Pending',
  logo_url text,
  squad_banner_url text,
  created_at timestamptz default now()
);

create table if not exists public.gallery_media (
  id text primary key,
  title text not null,
  type text default 'photos',
  category text default 'events',
  date date,
  url text,
  image_url text,
  created_at timestamptz default now()
);

create table if not exists public.news_updates (
  id text primary key,
  title text not null,
  tag text default 'Announcement',
  date date,
  summary text,
  image_url text,
  created_at timestamptz default now()
);

create table if not exists public.partners (
  id text primary key,
  name text not null,
  category text,
  link text,
  description text,
  status text default 'Published',
  logo_url text,
  created_at timestamptz default now()
);

create table if not exists public.contact_enquiries (
  id bigint generated by default as identity primary key,
  name text,
  mobile text,
  email text,
  enquiry_type text,
  message text,
  created_at timestamptz default now()
);

create table if not exists public.partner_enquiries (
  id bigint generated by default as identity primary key,
  name text,
  brand text,
  category text,
  mobile text,
  email text,
  message text,
  created_at timestamptz default now()
);

create table if not exists public.leadership_panel (
  id text primary key,
  name text not null,
  type text,
  designation text,
  bio text,
  photo_url text,
  created_at timestamptz default now()
);

alter table public.players enable row level security;
alter table public.teams enable row level security;
alter table public.gallery_media enable row level security;
alter table public.news_updates enable row level security;
alter table public.partners enable row level security;
alter table public.contact_enquiries enable row level security;
alter table public.partner_enquiries enable row level security;
alter table public.leadership_panel enable row level security;

